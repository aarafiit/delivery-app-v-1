/// Centralized spacing scale for the app.
/// Use these tokens for all padding, margin, and gap values.
/// Never use raw numeric literals for spacing in UI files.
class AppSpacing {
  AppSpacing._();

  /// 4.0 — micro spacing (icon gaps, tight rows)
  static const double xs = 4.0;

  /// 8.0 — small spacing (inner card padding, chip gaps)
  static const double sm = 8.0;

  /// 12.0 — medium spacing (list item padding, form gaps)
  static const double md = 12.0;

  /// 16.0 — large spacing (screen horizontal padding, section gaps)
  static const double lg = 16.0;

  /// 20.0 — extra large spacing (card padding, section separation)
  static const double xl = 20.0;

  /// 24.0 — 2x large spacing (hero sections, large gaps)
  static const double xxl = 24.0;

  /// 32.0 — 3x large spacing (screen top padding, major sections)
  static const double xxxl = 32.0;
}
